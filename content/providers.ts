/**
 * Lenders, providers and professional partners.
 *
 * ## Permission is the whole point of this file
 *
 * A lender's logo is that lender's trade mark. Having the file is not the same
 * as having the right to publish it, and an intermediary relationship is not
 * automatically a brand licence. So permission is data that has to be set
 * deliberately, per mark, rather than something a developer remembers to check.
 *
 * `isLogoPermitted` is the production rule and it fails closed. Every entry
 * below is `permissionConfirmed: false`, because no permission has been
 * recorded yet — see content/pending.ts providers.list.
 *
 * ## Development preview
 *
 * The firm supplied 37 marks and asked to see the marquee with real artwork
 * during review. `devLogoPreview` allows exactly that, and ONLY that:
 *
 *   - it is false whenever VERCEL_ENV === "production", so a production
 *     deployment can never publish an unpermissioned mark;
 *   - it is false under GUIDE_STRICT_CONTENT=1, so the launch-readiness build
 *     shows the same thing production would;
 *   - it can be forced off locally with GUIDE_DEV_LOGO_PREVIEW=0.
 *
 * The production gate is untouched by it. `isLogoPermitted` still returns false
 * for all 37, the marquee still labels itself as unapproved via PendingContent,
 * and `providers.list` still blocks launch. Setting permissionConfirmed on a
 * mark is what actually publishes it.
 *
 * ## Classification
 *
 * The supplied set mixes mortgage lenders, protection providers and
 * professional/platform partners. Nothing is classified yet — that is the
 * firm's call, and a wrong grouping asserts a relationship we cannot evidence.
 * Every entry is "unclassified" and the marquee shows them together. The
 * `category` axis exists so they can be split into Lenders / Providers /
 * Professional Partners later by editing data only: give each entry its
 * category and filter the list where it is consumed. No component changes.
 */

