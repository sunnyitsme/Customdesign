/**
 * The production rule. A mark is publishable only with permission on record.
 * Do not loosen this — loosen the data, per mark, once the evidence exists.
 */
export const isLogoPermitted = (provider: Provider): boolean =>
  provider.logo !== null &&
  provider.name !== null &&
  provider.permissionConfirmed &&
  provider.licenceRecord !== null;

/**
 * DEVELOPMENT ONLY — render supplied marks that have no permission recorded,
 * so the marquee can be reviewed with real artwork.
 *
 * Hard off in production. See the note at the top of this file.
 */
export const devLogoPreview: boolean =
  process.env.VERCEL_ENV !== "production" &&
  process.env.GUIDE_STRICT_CONTENT !== "1" &&
  process.env.GUIDE_DEV_LOGO_PREVIEW !== "0";

/** What the marquee actually renders, permission rule plus the dev preview. */
export const canDisplayLogo = (provider: Provider): boolean =>
  isLogoPermitted(provider) ||
  (devLogoPreview && provider.logo !== null && provider.name !== null);

/** Marks that will actually render right now. Empty in production today. */
export const displayableProviders = (): readonly Provider[] =>
  providers.filter(canDisplayLogo);

/** True when the strip is showing artwork nobody has cleared for publication. */
export const showingUnpermissionedPreview = (): boolean =>
  displayableProviders().some((provider) => !isLogoPermitted(provider));

