/**
 * Provisional grouping. Everything is "unclassified" until the firm confirms —
 * the other members exist so the split is a data change, not a refactor.
 */
export type ProviderCategory =
  | "lender"
  | "provider"
  | "professional-partner"
  | "unclassified";

export interface Provider {
  readonly id: string;
  /** Approved display name. Doubles as the mark's alt text. */
  readonly name: string | null;
  /** Path under /media/. Null until a file is supplied. */
  readonly logo: string | null;
  readonly category: ProviderCategory;
  /**
   * Written permission from the provider, or confirmed intermediary
   * brand-usage rights covering this site, evidenced in docs/media-licences/.
   * Never set true on the basis that a file was findable, or that the firm
   * happens to deal with that lender.
   */
  readonly permissionConfirmed: boolean;
  /** Licence record filename under docs/media-licences/. */
  readonly licenceRecord: string | null;
}

